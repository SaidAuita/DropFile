_CURRENT_LANG = "en"


def set_current_language(lang_code: str) -> None:
    global _CURRENT_LANG
    if lang_code in TRANSLATIONS:
        _CURRENT_LANG = lang_code
    else:
        _CURRENT_LANG = "en"


def get_current_language() -> str:
    return _CURRENT_LANG


def t(key: str, lang: Optional[str] = None, **kwargs: Any) -> str:
    """Translates key into the given or current language with English fallback."""
    code = lang or _CURRENT_LANG
    table = TRANSLATIONS.get(code, TRANSLATIONS["en"])
    template = table.get(key)
    if template is None:
        template = TRANSLATIONS["en"].get(key, key)
    if kwargs:
        try:
            return template.format(**kwargs)
        except Exception:
            return template
    return template
